class SymptomResolver(Protocol):
    async def resolve(self, text: str) -> str | None: ...


def normalize_text(text: str) -> str:
    """去標點空白、折疊異體字，並剝掉掛號意圖的包裝詞。"""
    cleaned = _PUNCTUATION_RE.sub("", text or "")
    cleaned = cleaned.translate(_VARIANT_FOLD)
    for pattern in _INTENT_PATTERNS:
        cleaned = re.sub(pattern, "", cleaned)
    return cleaned.strip()


class SymptomNormalizer:
    """口語症狀 → 對照表條目。表查不到才動用 LLM 兜底。"""

    def __init__(
        self,
        *,
        table_terms: tuple[str, ...],
        aliases: dict[str, str] | None = None,
        gemini_service: GeminiService | None = None,
        invoke: Callable[[str], Awaitable[dict[str, Any]]] | None = None,
        cache_size: int = DEFAULT_CACHE_SIZE,
        max_input_chars: int = DEFAULT_MAX_INPUT_CHARS,
    ) -> None:
        self._terms = tuple(table_terms)
        self._term_set = frozenset(self._terms)
        # 比對用索引：key 是折疊後的寫法，value 是表內的原始條目。
        # 直接拿原始條目當 key 會讓「筋骨痠痛」與「筋骨酸痛」變成兩個東西，
        # 而使用者打哪一種是隨機的。回傳一律是原始條目，SymptomTable 的 key
        # 沒有跟著改。
        self._lookup: dict[str, str] = {}
        for term in self._terms:
            self._lookup.setdefault(normalize_text(term), term)
        # 別名指向對照表不存在的條目時直接丟掉：留著只會在線上查到 None，
        # 比在啟動時少一條別名更難察覺。
        raw_aliases = SYMPTOM_ALIASES if aliases is None else aliases
        self._aliases = {
            normalize_text(key): value
            for key, value in raw_aliases.items()
            if value in self._term_set
        }
        dropped = len(raw_aliases) - len(self._aliases)
        if dropped:
            logger.warning(
                f"{LOGGER_HEADER_TEXT} %d 條同義詞指向對照表不存在的條目，已略過",
                dropped,
            )
        self._report_ineffective_aliases(raw_aliases)
        self._gemini = gemini_service
        self._invoke = invoke
        self._cache_size = cache_size
        self._max_input_chars = max_input_chars
        self._cache: dict[str, str | None] = {}
        self._schema = self._build_schema()

    def _report_ineffective_aliases(self, raw_aliases: dict[str, str]) -> None:
        """
        揪出「寫了但永遠不會生效」的別名，於啟動時記錄。

        兩種死法都不會拋錯，只會讓使用者拿到保底建議，從外面看起來像是
        「這個症狀沒收」：
          1. 被表內同名條目遮蔽——`便血` 本身就是條目，別名指向 `血便` 不會生效。
          2. 被 _INTENT_PATTERNS 折疊後互撞——`孩子沒胃口` 會被剝成 `沒胃口`，
             與另一條 `沒胃口` 撞 key，後寫的贏。
        這類錯誤靠讀 dict 幾乎看不出來，所以讓它在啟動日誌裡自己現形。
        """
        ineffective = [
            key
            for key, value in raw_aliases.items()
            if value in self._term_set and self.resolve_from_table(key) != value
        ]
        if ineffective:
            logger.warning(
                f"{LOGGER_HEADER_TEXT} %d 條同義詞不會生效（被條目遮蔽或 key 相撞）：%s",
                len(ineffective),
                "、".join(ineffective[:10]),
            )

    def _build_schema(self) -> dict[str, Any]:
        """輸出結構裡沒有科別欄位——模型沒有那個輸出通道。"""
        return {
            "type": "object",
            "properties": {
                "symptom": {"type": "string", "enum": [*self._terms, UNKNOWN]}
            },
            "required": ["symptom"],
        }

    def resolve_from_table(self, text: str) -> str | None:
        """只查表，不呼叫 LLM。供測試與想要零延遲的呼叫端使用。"""
        cleaned = normalize_text(text)
        if not cleaned:
            return None
        direct = self._lookup.get(cleaned)
        if direct is not None:
            return direct
        return self._aliases.get(cleaned)

    async def resolve(self, text: str) -> str | None:
        cleaned = normalize_text(text)
        if not cleaned:
            return None

        direct = self.resolve_from_table(cleaned)
        if direct is not None:
            return direct

        if len(cleaned) > self._max_input_chars:
            logger.info(
                f"{LOGGER_HEADER_TEXT} 說法過長（%d 字），略過 LLM 兜底", len(cleaned)
            )
            return None

        if cleaned in self._cache:
            return self._cache[cleaned]

        value = await self._classify(cleaned)
        self._remember(cleaned, value)
        return value

    async def _classify(self, text: str) -> str | None:
        prompt = (
            "你的任務：把使用者描述的身體不適，對應到候選清單裡的一個症狀條目。\n\n"
            "規則（必須嚴格遵守）：\n"
            "1. 只能從候選清單裡挑一個，不可自創清單以外的答案。\n"
            "2. 只做「同一個症狀的不同說法」的對應，例如「肚子痛」→「腹痛」。\n"
            "3. 不可做推論或診斷。使用者說「肚子痛」時，不可對應到「腸胃炎」"
            "或任何疾病名稱——那是醫療判斷，不在你的任務範圍內。\n"
            "4. 描述含糊、同時提到多個不相關症狀、或你無法確定時，一律回 "
            f"{UNKNOWN}。回 {UNKNOWN} 永遠比猜錯好。\n\n"
            f"候選清單：{'、'.join(self._terms)}\n\n"
            f"使用者描述：{text}"
        )
        try:
            raw = await self._call(prompt)
        except Exception:
            # 兜底層失效不該讓整條流程斷掉，降級成「表也查不到」，由服務層走保底。
            logger.warning(
                f"{LOGGER_HEADER_TEXT} LLM 兜底呼叫失敗，降級為解析失敗，text=%r",
                text,
                exc_info=True,
            )
            return None

        value = raw.get("symptom") if isinstance(raw, dict) else raw
        value = (str(value) if value is not None else "").strip()

        if not value or value == UNKNOWN:
            return None
        # enum 的強制力取決於模型與 SDK 實作，這裡再驗一次：放行清單外的值會讓
        # 後續查表靜默落空，退化成「系統說查過了但沒有結果」。
        if value not in self._term_set:
            logger.warning(
                f"{LOGGER_HEADER_TEXT} LLM 回傳候選清單以外的值 %r，視為解析失敗",
                value,
            )
            return None

        logger.info(f"{LOGGER_HEADER_TEXT} LLM 兜底成功，%r → %r", text, value)
        return value

    async def _call(self, prompt: str) -> dict[str, Any]:
        if self._invoke is not None:
            return await self._invoke(prompt)
        if self._gemini is None:
            raise RuntimeError("SymptomNormalizer requires gemini_service or invoke")
        structured = self._gemini.chat_model.with_structured_output(
            self._schema,
            method="json_schema",
        )
        result = await structured.ainvoke([HumanMessage(content=prompt)])
        if not isinstance(result, dict):
            raise ValueError(f"unexpected normalizer payload: {type(result)}")
        return result

    def _remember(self, key: str, value: str | None) -> None:
        if self._cache_size <= 0:
            return
        if len(self._cache) >= self._cache_size:
            self._cache.pop(next(iter(self._cache)))
        self._cache[key] = value
